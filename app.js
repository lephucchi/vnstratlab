"use strict";

// ---- language toggle (per-viewer convenience; works without storage)
const root = document.documentElement;
function setLang(lang) {
  root.lang = lang;
  document.getElementById("lang").textContent = lang === "vi" ? "EN" : "VI";
  try { localStorage.setItem("vnstratlab-lang", lang); } catch (_) { /* storage unavailable */ }
}
let initial = "vi";
try { initial = localStorage.getItem("vnstratlab-lang") || "vi"; } catch (_) { /* ignore */ }
setLang(initial);
document.getElementById("lang").addEventListener("click", () => setLang(root.lang === "vi" ? "en" : "vi"));

// ---- measured project status from CI (data/status.json, generated by pages.yml)
const T = {
  vi: { tests: "Test pass", cov: "Coverage", ci: "CI develop", cards: "Card hoàn thành", ok: "thành công", fail: "lỗi", running: "đang chạy",
        none: "chưa có dữ liệu", updated: "Cập nhật", commit: "commit", bench: "Benchmark mới nhất", nodata: "Chưa có số liệu đo." },
  en: { tests: "Tests passing", cov: "Coverage", ci: "CI on develop", cards: "Cards done", ok: "passing", fail: "failing", running: "running",
        none: "no data yet", updated: "Updated", commit: "commit", bench: "Latest benchmarks", nodata: "No measurements yet." },
};

function kpi(label, value, tone = "") {
  const d = document.createElement("div");
  d.className = "kpi";
  const l = document.createElement("div"); l.className = "label"; l.textContent = label;
  const v = document.createElement("div"); v.className = `value ${tone}`; v.textContent = value;
  d.append(l, v);
  return d;
}

function render(s) {
  const t = T[root.lang] || T.vi;
  const kpis = document.getElementById("kpis");
  if (!s) {
    kpis.replaceChildren(kpi(t.tests, "—"), kpi(t.cov, "—"));
    document.getElementById("status-meta").textContent = t.nodata;
    return;
  }
  const ci = s.last_ci;
  let ciText = t.none, ciTone = "";
  if (ci) {
    if (ci.status !== "completed") { ciText = t.running; }
    else if (ci.conclusion === "success") { ciText = t.ok; ciTone = "ok"; }
    else { ciText = t.fail; ciTone = "bad"; }
  }
  const failed = s.tests ? s.tests.failures + s.tests.errors : 0;
  kpis.replaceChildren(
    kpi(t.tests, s.tests ? `${s.tests.passed}/${s.tests.tests}` : "—", s.tests ? (failed ? "bad" : "ok") : ""),
    kpi(t.cov, s.coverage != null ? `${s.coverage}%` : "—"),
    kpi(t.ci, ciText, ciTone),
    kpi(t.cards, `${s.cards_done}/${s.cards_total}`),
  );
  const bench = document.getElementById("bench");
  bench.replaceChildren();
  if (s.benchmarks && s.benchmarks.length) {
    const h = document.createElement("p"); h.className = "muted small"; h.textContent = t.bench;
    const table = document.createElement("table"); table.className = "table";
    for (const b of s.benchmarks) {
      const tr = document.createElement("tr");
      const a = document.createElement("td"); a.textContent = b.name;
      const c = document.createElement("td"); c.textContent = `${Number(b.value).toPrecision(4)} ${b.unit} · ${b.commit}`;
      tr.append(a, c); table.append(tr);
    }
    bench.append(h, table);
  }
  const when = new Date(s.generated_at).toLocaleString(root.lang === "vi" ? "vi-VN" : "en-GB", { timeZone: "Asia/Ho_Chi_Minh", hour12: false });
  document.getElementById("status-meta").textContent = `${t.updated} ${when} · ${t.commit} ${s.commit || "—"}`;
}

let status = null;
fetch("data/status.json", { cache: "no-store" })
  .then((r) => (r.ok ? r.json() : null))
  .then((s) => { status = s; render(status); })
  .catch(() => render(null));
document.getElementById("lang").addEventListener("click", () => render(status));
