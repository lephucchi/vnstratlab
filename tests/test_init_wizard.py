def test_home_folders_created_and_existing_data_untouched(synthetic_home: Path) -> None:
    (synthetic_home / "data").mkdir(parents=True)
    keep = synthetic_home / "data" / "keep.bin"
    keep.write_bytes(b"abc")
    result = runner.invoke(app, ["init", "--yes"])
    assert result.exit_code == 0, result.output
    for name in ("data", "strategies", "logs", "backups"):
        assert (synthetic_home / name).is_dir()
    assert keep.read_bytes() == b"abc"


def test_secrets_never_read_printed_or_written(
    synthetic_home: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    monkeypatch.setenv("TELEGRAM_BOT_TOKEN", "CANARY" * 4)
    monkeypatch.setenv("PO_PASSWORD", "canary" * 4)
    result = runner.invoke(app, ["init", "--yes", "--source", "yahoo"])
    assert result.exit_code == 0, result.output
    assert ".env.example" in result.output
    blobs = [result.output] + [
        p.read_text(errors="ignore") for p in synthetic_home.rglob("*") if p.is_file()
    ]
    assert not any("CANARY" in blob.upper() for blob in blobs)
    assert not (synthetic_home / ".env").exists()


def test_yahoo_prints_terms_notice_and_records_no_acceptance(synthetic_home: Path) -> None:
    result = runner.invoke(app, ["init", "--yes", "--source", "yahoo"])
    assert result.exit_code == 0, result.output
    assert "interim source" in result.output
    assert "vnstratlab ingest" in result.output
    assert not list(synthetic_home.rglob("*accepted*"))
    assert not list((synthetic_home / "data").iterdir())


def test_yahoo_declined_falls_back_to_synthetic(synthetic_home: Path) -> None:
    result = runner.invoke(app, ["init"], input=_interactive("", "", "", "yahoo", "", "n"))
    assert result.exit_code == 0, result.output
    assert _user(synthetic_home) == {"data": {"source": "synthetic"}}
    assert "vnstratlab ingest" not in result.output


def test_write_is_atomic(synthetic_home: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    def boom(*_: object, **__: object) -> None:
        raise OSError("disk full")

    monkeypatch.setattr(init_wizard.os, "replace", boom)
    result = runner.invoke(app, ["init", "--yes"])
    assert result.exit_code != 0
    assert not (synthetic_home / "config.yaml").exists()
    assert not list(synthetic_home.glob(".config.yaml.*"))


def test_build_overrides_drops_default_values_and_empty_parents() -> None:
    defaults = {"books": {"short": {"capital_vnd": 10}}, "data": {"source": "yahoo"}}
    existing = {"books": {"short": {"capital_vnd": 99}}, "keep": 1}
    out = init_wizard.build_overrides(
        existing, capital={"short": 10, "long": None}, defaults=defaults
    )
    assert out == {"keep": 1}


def test_render_config_empty_and_nonempty() -> None:
    day = dt.date(2026, 11, 26)
    assert init_wizard.render_config({}, day).endswith("{}\n")
    assert "2026-11-26" in init_wizard.render_config({"a": 1}, day)
